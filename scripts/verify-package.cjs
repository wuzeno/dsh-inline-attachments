'use strict';
// Offline distribution smoke test; does not install into or mutate DSH.
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const archive = process.argv[2] || path.join(root, `${manifest.name}-${manifest.version}.tgz`);
const tar = zlib.gunzipSync(fs.readFileSync(archive));
const entries = new Map();
for (let offset = 0; offset + 512 <= tar.length;) {
  const header = tar.subarray(offset, offset + 512);
  if (header.every(byte => byte === 0)) break;
  const text = (start, end) => header.toString('utf8', start, end).replace(/\0.*$/s, '');
  const name = text(0, 100), prefix = text(345, 500);
  const key = prefix ? `${prefix}/${name}` : name;
  const size = parseInt(text(124, 136).trim() || '0', 8);
  assert.ok(Number.isSafeInteger(size) && size >= 0, 'Invalid tar entry length');
  assert.ok(offset + 512 + size <= tar.length, 'Truncated tar entry');
  assert.ok(!key.split('/').includes('..') && !key.startsWith('/'), 'Unsafe tar member path');
  const kind = text(156, 157);
  assert.ok(kind !== '1' && kind !== '2', 'Distribution must not contain linked files');
  if (kind === '' || kind === '0') entries.set(key, tar.subarray(offset + 512, offset + 512 + size));
  offset += 512 + Math.ceil(size / 512) * 512;
}
const content = name => { assert.ok(entries.has('package/' + name), `Missing package/${name}`); return entries.get('package/' + name).toString('utf8'); };
const packed = JSON.parse(content('package.json'));
assert.equal(packed.name, manifest.name); assert.equal(packed.version, manifest.version);
for (const target of Object.values(packed.exports)) content(target.replace(/^\.\//, ''));
content(packed.dsh.bundle.patch.replace(/^\.\//, ''));
content('README.md');
assert.match(content('LICENSE'), /MIT License/);
assert.match(content('LICENSE'), /Copyright/);
const generated = '/* Generated by scripts/build.cjs; edit src/ instead. */\n' + ['core.js', 'history.js', 'slot-mirror.js', 'client.js'].map(name => content('src/' + name)).join('\n;\n');
assert.equal(content('client.js'), generated, 'Packaged generated client differs from packaged sources');
let definition;
const sandbox = vm.createContext({ window: { __ModuleLoader__: { load(value) { assert.equal(definition, undefined, 'Multiple loader entries'); definition = value; } } } });
vm.runInContext(content('client.js'), sandbox, { filename: 'packaged-client.js', timeout: 2000 });
assert.equal(definition.id, packed.name);
assert.equal(typeof definition.factory, 'function');
const plugin = definition.factory(name => { assert.equal(name, 'react'); return { createElement() {} }; });
assert.equal(typeof plugin.apply, 'function');
assert.ok(plugin.inject.includes('slots') && plugin.inject.includes('inputTriggers'));
assert.equal(typeof sandbox.DshInlineAttachmentCore.encodeMarker, 'function');
assert.equal(typeof sandbox.DshInlineAttachmentHistory.create, 'function');
console.log(`Package verified: ${packed.name}@${packed.version}; ${entries.size} files; generated client and ModuleLoader entry match.`);
