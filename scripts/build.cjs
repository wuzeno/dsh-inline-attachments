'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const files = ['core.js', 'history.js', 'slot-mirror.js', 'client.js'];
const body = files.map(file => fs.readFileSync(path.join(root, 'src', file), 'utf8')).join('\n;\n');
fs.writeFileSync(path.join(root, 'client.js'), '/* Generated by scripts/build.cjs; edit src/ instead. */\n' + body);
console.log('Built client.js (' + Buffer.byteLength(body) + ' bytes)');
